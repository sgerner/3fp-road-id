-- Pre-2025 baseline schema for local Supabase CLI resets and CI verification.
-- Captures foundational extensions, schemas, roles/enums, tables, and triggers
-- that predated recorded migration history in supabase/migrations/.

create extension if not exists "uuid-ossp" with schema extensions;
create extension if not exists pgcrypto with schema extensions;
create extension if not exists citext with schema public;
create extension if not exists postgis with schema public;
create extension if not exists pg_cron;
create extension if not exists pg_net;

create schema if not exists private;
create schema if not exists map;

do $$
begin
	if not exists (
		select 1
		from pg_proc p
		join pg_namespace n on n.oid = p.pronamespace
		where n.nspname = 'map'
			and p.proname = 'get_improvements'
			and p.pronargs = 0
	) then
		execute $fn$
			create function map.get_improvements()
			returns jsonb
			language sql
			stable
			security invoker
			as $body$
				select '[]'::jsonb;
			$body$;
		$fn$;
	end if;
end $$;

do $$
begin
	if not exists (
		select 1
		from pg_type t
		join pg_namespace n on n.oid = t.typnamespace
		where n.nspname = 'public'
			and t.typname = 'group_member_role'
	) then
		create type public.group_member_role as enum ('owner', 'admin', 'editor', 'member');
	end if;
end $$;

create table if not exists public.profiles (
	id uuid primary key default gen_random_uuid(),
	user_id uuid not null unique references auth.users(id) on delete cascade,
	full_name text,
	avatar_url text,
	bio text,
	email text,
	phone text,
	emergency_contact_name text,
	emergency_contact_phone text,
	metadata jsonb not null default '{}'::jsonb,
	admin boolean not null default false,
	created_at timestamptz not null default timezone('utc', now()),
	updated_at timestamptz not null default timezone('utc', now())
);

do $$
begin
	if not exists (
		select 1
		from pg_proc p
		join pg_namespace n on n.oid = p.pronamespace
		where n.nspname = 'public'
			and p.proname = 'create_profile_on_new_user'
			and p.pronargs = 0
	) then
		execute $fn$
			create function public.create_profile_on_new_user()
			returns trigger
			language plpgsql
			security definer
			as $function$
			begin
				insert into public.profiles (user_id)
				values (new.id);

				return new;
			end;
			$function$;
		$fn$;
	end if;

	if not exists (
		select 1
		from pg_trigger t
		join pg_class c on c.oid = t.tgrelid
		join pg_namespace n on n.oid = c.relnamespace
		where n.nspname = 'auth'
			and c.relname = 'users'
			and t.tgname = 'new_user_profile_trigger'
			and not t.tgisinternal
	) then
		create trigger new_user_profile_trigger
			after insert on auth.users
			for each row execute function public.create_profile_on_new_user();
	end if;
end $$;

