-- Minimal app dependencies for an isolated local proximity RPC test database. Never run in production.
create schema extensions;
create function extensions.uuid_generate_v4() returns uuid language sql as 'select gen_random_uuid()';
create function extensions.gen_random_bytes(n integer) returns bytea language sql as 'select decode(repeat(''ab'',n),''hex'')';

create schema auth;
create table auth.users (
	id uuid primary key,
	email text
);
create function auth.uid() returns uuid language sql stable as
	'select nullif(current_setting(''request.jwt.claim.sub'', true), '''')::uuid';

create schema storage;
create table storage.buckets (
	id text primary key,
	name text,
	public boolean,
	file_size_limit bigint,
	allowed_mime_types text[]
);
create table storage.objects (
	id uuid primary key default gen_random_uuid(),
	name text,
	bucket_id text
);
create function storage.foldername(name text) returns text[] language sql immutable as
	'select string_to_array(name, ''/'')';

create table public.groups (
	id uuid primary key default gen_random_uuid(),
	slug text not null unique,
	name text not null,
	tagline text,
	description text,
	membership_info text,
	service_area_description text,
	city text,
	state_region text,
	country text default 'US',
	logo_url text,
	cover_photo_url text,
	latitude double precision,
	longitude double precision,
	is_published boolean not null default true
);

create table public.group_members (
	group_id uuid not null references public.groups(id) on delete cascade,
	user_id uuid not null references auth.users(id) on delete cascade,
	role text not null,
	primary key (group_id, user_id)
);

create table public.riding_disciplines (
	id integer generated by default as identity primary key,
	name text not null
);

create table public.group_x_group_types (
	group_id uuid not null references public.groups(id) on delete cascade,
	group_type_id integer not null
);

create table public.group_x_audience_focuses (
	group_id uuid not null references public.groups(id) on delete cascade,
	audience_focus_id integer not null
);

create table public.group_x_riding_disciplines (
	group_id uuid not null references public.groups(id) on delete cascade,
	riding_discipline_id integer not null
);

create table public.emergency_contacts (
	id uuid primary key default gen_random_uuid()
);

create schema cron;
create table cron.job (
	jobid bigint generated by default as identity primary key,
	jobname text,
	schedule text,
	command text
);
create function cron.unschedule(target_job_id bigint) returns boolean language sql as 'select true';
create function cron.schedule(p_name text, p_schedule text, p_command text) returns bigint language sql as 'select 1::bigint';

grant usage on schema public to anon, authenticated, service_role;
